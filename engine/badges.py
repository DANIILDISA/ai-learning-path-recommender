"""Бейджи карточки: факты, а не оценка.

Каждый бейдж один к одному соответствует слагаемому, которое сработало в
`engine.scoring`, и несёт ровно тот текст обоснования, который движок уже
посчитал. Пересказ факта своими словами означал бы вторую формулировку одного
и того же -- она начнёт расходиться с первой при первой же правке.

Единственный оценочный бейдж -- «Высокое соответствие», и считается он по
**числу сработавших факторов**, а не по баллу. Порог по баллу поставить
нельзя: у 18 профилей из 323 нет когорты коллег, их peer-слагаемые всегда
нулевые, и потолок балла у этих людей структурно ниже. Такой порог наказывал
бы их за дефект выгрузки, а не за качество подбора, и человеку без коллег
система сообщала бы, что все его рекомендации так себе.

Порог = 3 выбран замером на всех 323 профилях
(`docs-internal/продукт-3/tools/measure_badges.py`): бейдж достаётся 35,9%
карточек, и хотя бы одна такая карточка есть у 273 профилей. При пороге 2
бейдж был бы у 98,3% рекомендаций, то есть не значил бы ничего.
"""
from __future__ import annotations

from dataclasses import dataclass

# Тексты, которые `engine.scoring._fallback_reason` выдаёт, когда за курс не
# нашлось ни одного довода. Это не аргументы за программу, а честное
# признание, что аргументов нет, -- и в счёт факторов они не идут.
_FALLBACKS = (
    "Программа адресована категории «руководители»",
    "Программа открыта для всех государственных гражданских служащих",
)

HIGH_MATCH_FACTORS = 3

# Начало строки обоснования -> вид бейджа. Порядок кортежа задаёт порядок
# бейджей на карточке и потому зафиксирован: воспроизводимость выдачи -- это
# требование приёмки, и она распространяется на всё, что видит человек.
_KIND_BY_PREFIX = (
    ("Программа входит в трек", "navigator"),
    ("Ваш интерес:", "interest"),
    ("Вы отметили эту программу", "picked"),
    ("Отвечает вашей цели:", "goal"),
    ("Можно пройти дистанционно", "urgency"),
    ("Короткая программа", "urgency"),
    ("Электронный курс —", "urgency"),
    ("По направлению", "gap"),
    ("Курс отмечен как «не пройден»", "unfinished"),
    ("Курс отмечен как «в процессе»", "unfinished"),
)


@dataclass(frozen=True)
class Badge:
    """Метка на карточке: вид -- для оформления, текст -- для человека."""

    kind: str
    text: str


def factor_count(reasons: list[str]) -> int:
    """Сколько настоящих доводов стоит за рекомендацией."""
    return sum(1 for reason in reasons if not reason.startswith(_FALLBACKS))


def _kind_of(reason: str) -> str | None:
    for prefix, kind in _KIND_BY_PREFIX:
        if reason.startswith(prefix):
            return kind
    # Обоснование про коллег начинается с числа («82% коллег ...»), поэтому
    # устойчивого зачина у него нет и по префиксу оно не ловится.
    if reason[:1].isdigit() and "коллег" in reason:
        return "peers"
    return None


def badges_for(reasons: list[str], position: int) -> list[Badge]:
    """Бейджи одной карточки.

    `position` -- место в маршруте, считая с единицы. Оно приходит снаружи,
    потому что «начать отсюда» -- свойство порядка, а не курса: одна и та же
    программа стоит первой у одного человека и четвёртой у другого.

    Обоснование, которого нет в таблице видов, бейджа не даёт. Это осознанно:
    новый текст в `engine.scoring` лучше пропустить, чем показать человеку
    метку без оформления и без смысла.
    """
    badges: list[Badge] = []
    if position == 1:
        badges.append(Badge("start_here", "Рекомендуем начать с этого"))

    for reason in reasons:
        kind = _kind_of(reason)
        if kind is not None:
            badges.append(Badge(kind, reason))

    if factor_count(reasons) >= HIGH_MATCH_FACTORS:
        badges.append(Badge("high_match", "Высокое соответствие"))
    return badges
